import asyncio, sys, json, math
from playwright.async_api import async_playwright
import os
OUT=os.environ.get('CIN_OUT','/tmp/svgcinema-shots/'); os.makedirs(OUT, exist_ok=True)
# UI polish: the timeline's top edge resizes it (min / max / saved / reset / keys; the canvas zoom stays
# unless the view is fitted), pins bound to bones in the playhead red, dotted links between bones bound
# with the Bind tool (from the parent's joint; shown with the bones, never exported), sliders centred on
# their row, double-click renames in the Layers panel and the timeline, drag-to-change on number
# field labels everywhere (one undo step, no focus after a drag), the Size "Keep proportions" toggle,
# and the toggle column that keeps paired fields the same width.
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); ctx=await b.new_context(color_scheme='light'); pg=await ctx.new_page()
        await pg.set_viewport_size({'width':1440,'height':900}); pg.set_default_timeout(5000)
        errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
        url=(sys.argv[1] if len(sys.argv)>1 else 'http://localhost:5199/')
        await pg.goto(url, wait_until='domcontentloaded'); await pg.wait_for_timeout(2500)
        await pg.evaluate("localStorage.removeItem('svgcinema:tlH')")
        await pg.reload(wait_until='domcontentloaded'); await pg.wait_for_timeout(2000)
        imp="async()=>{ window.st=await import('/src/core/state.ts'); window.hi=await import('/src/core/history.ts'); window.ov=await import('/src/render/overlay.ts'); window.B=await import('/src/export/build.ts'); window.PP=await import('/src/ui/props-panel.ts'); window.TR=await import('/src/ui/tl-resize.ts'); window.ha=await import('/src/tools/hand.ts'); window.BO=await import('/src/tools/bones.ts'); window.SG=await import('/src/render/stage.ts'); }"
        await pg.evaluate(imp)
        ev=pg.evaluate; R={}; F=[]
        def check(n,c,i=None):
            R[n]=('ok' if c else 'FAIL')+('' if i is None else f' {i}')
            if not c: F.append(n)
        lid=lambda n: ev(f"st.doc.layers.find(l=>l.name==='{n}').id")
        tlh=lambda: ev("Math.round(document.querySelector('.panel.tl').getBoundingClientRect().height)")

        # ---- 1. timeline height
        check('the timeline starts at its default height', await tlh()==288, await tlh())
        g=await pg.locator('#tlGrip').bounding_box()
        check('a grip on its top edge with a resize cursor', g and abs(g['y']-(900-288))<2 and await ev("getComputedStyle(tlGrip).cursor")=='ns-resize', g)
        async def grip(y):
            g=await pg.locator('#tlGrip').bounding_box()
            await pg.mouse.move(600,g['y']+3); await pg.mouse.down(); await pg.mouse.move(600,(g['y']+y)/2,steps=3); await pg.mouse.move(600,y,steps=3); await pg.mouse.up(); await pg.wait_for_timeout(150)
        await grip(500)
        check('dragging the edge up makes it taller by as much', abs(await tlh()-(288+g['y']+3-500))<=1, await tlh())
        await grip(899)
        mn=await tlh()
        want=await ev("(()=>{const t=document.querySelector('.panel.tl');return t.querySelector('.tl-ctrl').offsetHeight+t.querySelector('.tl-ruler').offsetHeight})()")
        vis=await ev("(()=>{const r=document.querySelector('.tl-ruler').getBoundingClientRect(),s=tlscroll.getBoundingClientRect();return r.bottom<=s.bottom+1})()")
        rows=await ev("(()=>{const r=document.querySelector('.tl-body > .tl-row:not(.tl-ruler)').getBoundingClientRect(),s=tlscroll.getBoundingClientRect();return Math.max(0,Math.min(r.bottom,s.bottom)-Math.max(r.top,s.top))})()")
        check('smallest: just the controls and the time ruler, no rows', mn>=want and mn<=want+18 and vis and rows<=3, (mn,want,vis,rows))
        await grip(0)
        mx=await tlh(); wrap=await ev("Math.round(document.getElementById('wrap').getBoundingClientRect().height)")
        check('largest: a strip of the work area stays', wrap>=118 and wrap<=125 and mx>600, (mx,wrap))
        await pg.screenshot(path=OUT+'ui-polish-tl-max.png')
        await grip(560)
        h=await tlh()
        check('the height is saved', await ev("localStorage.getItem('svgcinema:tlH')")==str(h), h)
        await pg.reload(wait_until='domcontentloaded'); await pg.wait_for_timeout(1500); await pg.evaluate(imp)
        check('and kept after a reload', abs(await tlh()-h)<=1, (await tlh(),h))
        await pg.focus('#tlGrip'); await pg.keyboard.press('ArrowUp')
        check('↑ on the focused edge nudges it taller', abs(await tlh()-(h+16))<=1 and await ev("st.S.time")==0, await tlh())
        await pg.locator('#tlGrip').dblclick(); await pg.wait_for_timeout(100)
        check('double-click goes back to the default height', await tlh()==288, await tlh())
        await ev("hi.setTime(0)")

        # canvas zoom while resizing: kept (and the artwork stays put) unless the view is fitted
        await ev("ha.fitView()"); await pg.wait_for_timeout(100)
        await ev("ha.zoomTo(2)"); await pg.wait_for_timeout(100)
        art=lambda: ev("(()=>{const r=document.getElementById('artboard').getBoundingClientRect();return [Math.round(r.left),Math.round(r.top)]})()")
        z0=await ev("zValT.textContent"); a0=await art()
        await grip(420); await pg.wait_for_timeout(150)
        z1=await ev("zValT.textContent"); a1=await art()
        check('resizing keeps the zoom percentage', z0=='200%' and z1==z0 and abs(await ev("st.S.scale")-2)<1e-6, (z0,z1))
        check('and the artwork where it was on screen', abs(a1[0]-a0[0])<=1 and abs(a1[1]-a0[1])<=1, (a0,a1))
        await grip(800); await pg.wait_for_timeout(150)
        check('also when the timeline gets shorter', await ev("zValT.textContent")=='200%' and await art()==a0, (await ev("zValT.textContent"), await art()))
        await ev("ha.fitView()"); await pg.wait_for_timeout(100)
        f0=await ev("st.S.scale")
        await grip(420); await pg.wait_for_timeout(150)
        f1=await ev("st.S.scale")
        check('in the fit view the artboard is fitted again', f1<f0 and await ev("ha.isFitView()") and abs(f1-await ev("SG.fitScale()"))<1e-6, (f0,f1))
        await pg.locator('#tlGrip').dblclick(); await pg.wait_for_timeout(150)

        # sliders sit centred on their row
        await ev(f"hi.select('{await lid('Sky')}')"); await pg.wait_for_timeout(150)
        off=await ev("[...document.querySelectorAll('#insp .row input[type=range]')].filter(e=>e.offsetParent).map(e=>{const r=e.getBoundingClientRect(),q=e.closest('.row').getBoundingClientRect();return Math.round((r.top+r.height/2)-(q.top+q.height/2))})")
        check('sliders are centred on their row', len(off)>=2 and all(abs(o)<=1 for o in off), off)

        # ---- 2 & 4. bound pins in red, bone links
        await ev("hi.setTime(2.2)")
        await ev(f"hi.select('{await lid('Tendril')}')"); await ev("hi.setTool('pin')"); await pg.wait_for_timeout(200)
        red=await ev("getComputedStyle(document.getElementById('playhead')).backgroundColor")
        # (the selected pin is filled with the colour instead)
        bp=await ev("[...document.querySelectorAll('.ov-pin.is-bound')].map(e=>getComputedStyle(e)[e.classList.contains('is-sel')?'fill':'stroke'])")
        check('pins bound to bones are drawn in the playhead red', len(bp)==3 and all(s==red for s in bp), (bp,red))
        check('their ring and centre dot too', await ev(f"[...document.querySelectorAll('.ov-pinbound, .ov-pindot.is-bound')].every(e=>getComputedStyle(e).stroke==='{red}'||getComputedStyle(e).fill==='{red}')") and await ev("document.querySelectorAll('.ov-pinbound').length")==3)
        check('their chips in the Pins section are red-edged', await ev("document.querySelectorAll('.pin-chip.bound').length")==3 and red.replace('rgb(','').split(',')[0] in await ev("getComputedStyle(document.querySelector('.pin-chip.bound:not(.on)')).boxShadow"))
        await ev(f"hi.select('{await lid('Leaf')}')"); await pg.wait_for_timeout(150)
        free=await ev("[...document.querySelectorAll('.ov-pin:not(.is-bound)')].map(e=>getComputedStyle(e)[e.classList.contains('is-sel')?'fill':'stroke'])")
        check('ordinary pins keep the accent colour', free and all(s!=red for s in free), free)
        await pg.screenshot(path=OUT+'ui-polish-pins.png')
        await ev("hi.setTool('select')"); await pg.wait_for_timeout(150)
        # (2.2 s: the Sprout has grown from scale 0)
        check('a connected chain of bones needs no links', await ev("document.querySelectorAll('.ov-blink').length")==0, await ev("document.querySelectorAll('.ov-blink').length"))
        # a bone bound to Stem away from its tip (as the Bind tool leaves it)
        spur=await ev(f"""(()=>{{const l=st.mkLayer('bone','Spur',{{x:612,y:284,len:14,ang:0}},{{fill:'none'}});l.o=[612,284];l.parent='{await lid('Stem')}';st.doc.layers.push(l);SG.renderAll();ov.drawOverlay();return l.id}})()""")
        ln=await ev("[...document.querySelectorAll('.ov-blink')].map(e=>[e.dataset.blink,e.dataset.child,+e.getAttribute('x1'),+e.getAttribute('y1'),+e.getAttribute('x2'),+e.getAttribute('y2')])")
        pj=await ev(f"(()=>{{const p=BO.bonePts(st.layerById('{await lid('Stem')}')).J;return [p.x,p.y]}})()")
        cj=await ev(f"(()=>{{const p=BO.bonePts(st.layerById('{spur}')).J;return [p.x,p.y]}})()")
        check('a dotted link from the parent bone to a bound bone', len(ln)==1 and ln[0][:2]==[await lid('Stem'),spur], ln)
        check('it starts at the parent bone\'s joint (its start) and ends at the bound bone\'s joint', ln and abs(ln[0][2]-pj[0])<0.02 and abs(ln[0][3]-pj[1])<0.02 and abs(ln[0][4]-cj[0])<0.02 and abs(ln[0][5]-cj[1])<0.02, (ln,pj,cj))
        check('drawn dotted', await ev("getComputedStyle(document.querySelector('.ov-blink')).strokeDasharray")!='none')
        check('no links to layers or pins', await ev("[...document.querySelectorAll('.ov-blink')].every(e=>st.layerById(e.dataset.child).type==='bone')"))
        await ev("st.S.showBones=false; ov.drawOverlay()")
        check('hidden with Show bones off', await ev("document.querySelectorAll('.ov-blink').length")==0 and await ev("document.querySelectorAll('.ov-bone').length")==0)
        await ev("st.S.showBones=true; ov.drawOverlay()")
        await ev(f"st.layerById('{spur}').hid=true; ov.drawOverlay()")
        check('a hidden bone shows no link', await ev("document.querySelectorAll('.ov-blink').length")==0)
        await ev(f"st.layerById('{spur}').hid=false; ov.drawOverlay()")
        out=await ev("B.buildExport(null)")
        check('links are not in the export', 'ov-blink' not in out and 'blink' not in out)
        await ev(f"st.doc.layers.splice(st.doc.layers.findIndex(l=>l.id==='{spur}'),1); SG.renderAll()")
        await ev("hi.setTime(0)")

        # ---- 3. rename by double-click
        await ev("hi.select(null)"); await pg.wait_for_timeout(100)
        sid=await lid('Signature')
        await pg.locator(f'.lp-row[data-lid="{sid}"] .lp-name').dblclick(); await pg.wait_for_timeout(150)
        check('double-click a name in the Layers panel to rename it', await ev("document.activeElement && document.activeElement.matches('.lp-name input')"))
        u0=await ev("st.S.undo.length")
        await pg.keyboard.press('Control+a'); await pg.keyboard.type('Sig'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(150)
        check('Enter keeps the new name (one undo step)', await ev(f"st.layerById('{sid}').name")=='Sig' and await ev("st.S.undo.length")==u0+1)
        await pg.locator(f'.lp-row[data-lid="{sid}"] .lp-name').dblclick(); await pg.wait_for_timeout(150)
        await pg.keyboard.type('zzz'); await pg.keyboard.press('Escape'); await pg.wait_for_timeout(150)
        check('Escape cancels', await ev(f"st.layerById('{sid}').name")=='Sig' and not await ev("!!document.querySelector('.lp-name input')"))
        await pg.locator(f'.lp-row[data-lid="{sid}"] .lp-name').click(); await pg.wait_for_timeout(700)
        await pg.locator(f'.lp-row[data-lid="{sid}"] .lp-name').click(); await pg.wait_for_timeout(150)
        check('two slow clicks do not rename', not await ev("!!document.querySelector('.lp-name input')"))
        tid=await lid('Title')
        await pg.locator(f'.tl-layer[data-lid="{tid}"] .tl-lname').dblclick(); await pg.wait_for_timeout(150)
        check('and in the timeline', await ev("document.activeElement && document.activeElement.matches('.tl-lname input')"))
        await pg.keyboard.press('Escape')

        # ---- 5. drag a field's label to change the value
        async def scrub(inp, dx=30, mods=None):
            await pg.locator('#'+inp).scroll_into_view_if_needed()
            bb=await pg.locator(f'.nf:has(#{inp}) > span, .tl-len:has(#{inp}) > span').first.bounding_box()
            x,y=bb['x']+bb['width']/2, bb['y']+bb['height']/2
            if mods: await pg.keyboard.down(mods)
            await pg.mouse.move(x,y); await pg.mouse.down()
            for i in range(1,7): await pg.mouse.move(x+dx*i/6,y); await pg.wait_for_timeout(25)
            await pg.mouse.up(); await pg.wait_for_timeout(150)
            if mods: await pg.keyboard.up(mods)
        sky=await lid('Sky')
        await ev(f"hi.select('{sky}')"); await pg.wait_for_timeout(150)
        for inp,key,dx,want in [('g-x',"geo.x",30,30),('i-pos_0',"b.pos[0]",30,30)]:
            u0=await ev("st.S.undo.length")
            await scrub(inp,dx)
            v=await ev(f"st.layerById('{sky}').{key}")
            check(f'drag the label of {inp}', v==want and await ev("st.S.undo.length")==u0+1, (v,await ev("st.S.undo.length")-u0))
        check('a drag does not leave the field focused', await ev("!document.activeElement || document.activeElement.tagName!=='INPUT'"))
        await ev("hi.undo()"); await ev("hi.undo()")
        check('one undo per drag', await ev(f"st.layerById('{sky}').geo.x")==0)
        await scrub('tDur', 20)
        check('timeline length (0.05 s per pixel)', abs(await ev("st.doc.dur")-4)<1e-6, await ev("st.doc.dur"))
        await ev("hi.undo()")
        await scrub('g-x', 20, 'Shift')
        check('Shift: ten times faster', await ev(f"st.layerById('{sky}').geo.x")==200, await ev(f"st.layerById('{sky}').geo.x"))
        await ev("hi.undo()")
        await ev(f"hi.select('{tid}')"); await pg.wait_for_timeout(150)
        await scrub('g-size', 10)
        check('text size', await ev(f"st.layerById('{tid}').geo.size")==50, await ev(f"st.layerById('{tid}').geo.size"))
        await ev("hi.undo()")
        await ev("hi.select(null)"); await pg.wait_for_timeout(150)
        await scrub('d-w', 10)
        check('document width (no layer selected)', await ev("st.doc.w")==650, await ev("st.doc.w"))
        await ev("hi.undo()")
        bb=await pg.locator('.nf:has(#d-w) > span').bounding_box(); await pg.mouse.click(bb['x']+3,bb['y']+3); await pg.wait_for_timeout(80)
        check('a plain click on the label still focuses the field', await ev("document.activeElement.id")=='d-w')
        await pg.keyboard.press('Escape')

        # ---- 6. Size: Keep proportions toggle
        await ev(f"hi.select('{sky}')"); await pg.wait_for_timeout(150)
        row=await ev("(()=>{const r=document.querySelector('#i-sz_0').closest('.row');return [r.querySelector('.rl').textContent,[...r.querySelectorAll('.rf > *')].map(e=>e.className.split(' ')[0]+(e.dataset.act?':'+e.dataset.act:''))]})()")
        check('Size has a Keep proportions toggle beside its fields', row==['Size',['nf','nf','btn:szlock']], row)
        check('no separate Keep proportions checkbox', not await ev("!!document.getElementById('lockAR')"))
        check('off by default for shapes, on for images', await ev("document.querySelector('[data-act=szlock]').getAttribute('aria-pressed')")=='false' and await ev("PP.szLocked({type:'image'})") and not await ev("PP.szLocked({type:'rect'})"))
        await pg.click('[data-act=szlock]'); await pg.wait_for_timeout(80)
        await pg.fill('#i-sz_0','320'); await pg.press('#i-sz_0','Tab'); await pg.wait_for_timeout(150)
        check('with it on, W changes H in proportion', await ev(f"st.layerById('{sky}').b.sz || st.layerById('{sky}').geo")and await ev("document.getElementById('i-sz_1').value")=='200', await ev("document.getElementById('i-sz_1').value"))
        check('the toggle shows on', await ev("document.querySelector('[data-act=szlock]').classList.contains('on')"))
        await pg.click('[data-act=szlock]'); await ev("hi.undo()")

        # ---- 7. the toggle column
        wid=await ev("(()=>{const w=id=>Math.round(document.getElementById(id).closest('.nf').getBoundingClientRect().width);return {pos:w('i-pos_0'),scl:w('i-scl_0_100'),skw:w('i-skw_0'),org:w('i-org_0'),sz:w('i-sz_0'),gx:w('g-x')}})()")
        check('paired fields all keep the same width, toggle or not', len(set(wid.values()))==1, wid)
        tg=await ev("[...document.querySelectorAll('#insp [data-act=scllock], #insp [data-act=center], #insp [data-act=szlock]')].map(e=>{const r=e.getBoundingClientRect();return Math.round(r.left)+':'+Math.round(r.width)})")
        check('toggles sit in one column', len(set(tg))==1, tg)
        await pg.screenshot(path=OUT+'ui-polish-insp.png', clip={'x':1144,'y':52,'width':296,'height':560})

        R['errors']=errs; print(json.dumps(R,indent=1,ensure_ascii=False)); print('FAILS',F+(['errors'] if errs else []))
        await b.close()
asyncio.run(main())
