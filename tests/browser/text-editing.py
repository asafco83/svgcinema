import asyncio, sys, json, base64
from playwright.async_api import async_playwright
import os
OUT=os.environ.get('CIN_OUT','/tmp/svgcinema-shots/'); os.makedirs(OUT, exist_ok=True)
WOFF=base64.b64encode(open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','fixtures','heebo-latin-400-normal.woff'),'rb').read()).decode()
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await b.new_page(device_scale_factor=1)
        await pg.set_viewport_size({'width':1440,'height':1000}); pg.set_default_timeout(6000)
        await pg.add_init_script("""window.queryLocalFonts=async()=>{const bin=atob('%s');const u=new Uint8Array(bin.length);for(let i=0;i<bin.length;i++)u[i]=bin.charCodeAt(i);
          const mk=(st)=>({family:'My Local Sans',fullName:'My Local Sans '+st,postscriptName:'MyLocalSans-'+st,style:st,blob:async()=>new Blob([u])});return [mk('Regular'),mk('Bold')]}""" % WOFF)
        errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
        await pg.goto((sys.argv[1] if len(sys.argv)>1 else 'http://localhost:5199/'), wait_until='domcontentloaded'); await pg.wait_for_timeout(2500)
        await pg.evaluate("async()=>{ window.st=await import('/src/core/state.ts'); window.hi=await import('/src/core/history.ts'); window.B=await import('/src/export/build.ts')}")
        ev=lambda js: pg.evaluate(js); R={}; F=[]
        def check(n,c,i=None):
            R[n]=('ok' if c else 'FAIL')+('' if i is None else f' {i}')
            if not c: F.append(n)
        print(await ev("Object.keys(st).slice(0,12).join()"), errs)
        await ev("hi.setTime(2)")
        tid=await ev("st.doc.layers.find(l=>l.name==='Title').id"); L=f"st.layerById('{tid}')"
        await ev(f"hi.select('{tid}')")
        r=await ev(f"(()=>{{const r=document.getElementById('e-{tid}-s').getBoundingClientRect();return [r.x+r.width/2,r.y+r.height/2,r.x,r.y,r.width,r.height]}})()")
        r[0]=r[2]+r[4]*0.08
        print('hit', await ev(f"(()=>{{const e=document.elementFromPoint({r[0]},{r[1]});return e.tagName+' '+(e.closest('[data-lid]')||{{}}).id}})()"), await ev("st.S.sel"))
        await pg.mouse.dblclick(r[0],r[1]); await pg.wait_for_timeout(200)
        ta=await ev("(()=>{const t=document.querySelector('.cin-tedit');if(!t)return null;const b=t.getBoundingClientRect();return [b.x,b.y,b.width,b.height,document.activeElement===t]})()")
        check('double-click opens the editor on the canvas', ta and ta[4], ta)
        if ta: check('editor sits over the text', abs(ta[0]-r[2])<25 and abs(ta[1]+ta[3]/2-(r[3]+r[5]/2))<12, (ta,r[2:]))
        # the second press lands in an editor that waited over the text, so the browser focuses it itself
        # (Chrome then spell-checks the text at once) and puts the caret where the press was
        check('double-click: the browser focuses the waiting editor, caret at the press', await ev("(()=>{const t=document.querySelector('.cin-tedit');return !t.classList.contains('armed') && t.selectionStart<4})()"), await ev("document.querySelector('.cin-tedit').selectionStart"))
        check('svg text stays visible under a see-through editor', not await ev(f"document.getElementById('e-{tid}-s').getAttribute('visibility')") and await ev("getComputedStyle(document.querySelector('.cin-tedit')).color")=='rgba(0, 0, 0, 0)')
        playing0=await ev("st.S.playing")
        await pg.keyboard.press('End'); await pg.keyboard.type(' big world')
        check('typing updates the layer live', await ev(f"{L}.geo.text")=='Good morning big world', await ev(f"{L}.geo.text"))
        check('space does not play', await ev("st.S.playing")==playing0)
        check('inspector follows', await ev("document.getElementById('g-text').value")=='Good morning big world')
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(100)
        check('Esc ends editing', await ev("!document.querySelector('.cin-tedit')") and await ev(f"!document.getElementById('e-{tid}-s').getAttribute('visibility')"))
        await pg.keyboard.press('Control+z')
        check('one undo step', await ev(f"{L}.geo.text")=='Good morning', await ev(f"{L}.geo.text"))
        # a single click arms an editor for the double-click time only, then it goes away
        await pg.mouse.click(r[0],r[1]); await pg.wait_for_timeout(50)
        check('single click: an editor waits for a second press', await ev("!!document.querySelector('.cin-tedit.armed')"))
        await pg.wait_for_timeout(500)
        check('…and goes away after the double-click time', await ev("!document.querySelector('.cin-tedit')"))
        # inspector live typing
        await ev(f"hi.select('{tid}')")
        await pg.click('#g-text'); await pg.keyboard.press('End'); await pg.keyboard.type('!!')
        check('panel typing updates the canvas live', (await ev(f"document.getElementById('e-{tid}-s').textContent")).endswith('!!'))
        await pg.keyboard.press(' ')
        check('space in panel does not play', await ev("st.S.playing")==playing0)
        await pg.click('#ln')
        # selected (not editing): side handles scale; the edit-mode width handles are tested in te3
        await ev(f"hi.select('{tid}')"); await pg.wait_for_timeout(100)
        h=await ev("(()=>{const e=document.querySelector('#overlay [data-h=e]').getBoundingClientRect();return [e.x+e.width/2,e.y+e.height/2]})()")
        sc0=await ev(f"JSON.stringify({L}.b.scl)")
        await pg.mouse.move(h[0],h[1]); await pg.mouse.down(); await pg.mouse.move(h[0]-60,h[1],steps=6); await pg.mouse.up()
        check('selected text: side handle scales', await ev(f"JSON.stringify({L}.b.scl)")!=sc0 and not await ev(f"{L}.geo.wrap"))
        # text tool drag creates a box
        n0=await ev("st.doc.layers.length")
        await pg.keyboard.press('t')
        await pg.mouse.move(500,250); await pg.mouse.down(); await pg.mouse.move(700,300,steps=5); await pg.mouse.up(); await pg.wait_for_timeout(150)
        nl=await ev("st.selLayer()")
        check('text tool drag makes a fixed-width box and starts typing', await ev("st.doc.layers.length")==n0+1 and nl['geo'].get('wrap') and await ev("!!document.querySelector('.cin-tedit')"), nl and nl['geo'])
        await pg.keyboard.type('Hello there')
        check('typing replaces the placeholder', await ev("st.selLayer().geo.text")=='Hello there')
        await pg.mouse.click(1000,700); await pg.wait_for_timeout(100)
        check('click away ends editing', await ev("!document.querySelector('.cin-tedit')"))
        # path node section
        await ev(f"hi.select('{tid}')")
        sun=await ev("st.doc.layers.find(l=>l.name==='Sun').id")
        await pg.select_option('#motionPath', sun); await ev("hi.setTime(0)"); await pg.wait_for_timeout(100)
        sub=await ev("[...document.querySelectorAll('#insp .sub')].map(s=>s.textContent.trim()).find(s=>s.startsWith('Path node'))")
        check('path node section', sub and '1 of 5' in sub, sub)
        types=await ev("[...document.querySelectorAll('[data-act=ntype]')].map(b=>b.dataset.v+(b.classList.contains('on')?'*':''))")
        check('node type buttons with current type', len(types)==4 and any(t.endswith('*') for t in types), types)
        await ev("hi.setTime(0.5)"); await pg.wait_for_timeout(100)
        sub2=await ev("[...document.querySelectorAll('#insp .sub')].map(s=>s.textContent.trim()).find(s=>s.startsWith('Path node'))")
        check('between keys: previous node', sub2 and '1 of 5' in sub2 and 'before' in sub2, sub2)
        await pg.click('[data-act=nodego][data-d="1"]'); await pg.wait_for_timeout(100)
        sub3=await ev("[...document.querySelectorAll('#insp .sub')].map(s=>s.textContent.trim()).find(s=>s.startsWith('Path node'))")
        check('next node button', sub3 and '2 of 5' in sub3, sub3)
        await pg.click('[data-act=ntype][data-v=straight]')
        check('straight node', await ev(f"{L}.t.pos[1][4]")=='straight' and await ev("document.querySelector('[data-act=ntype][data-v=straight]').classList.contains('on')"))
        await pg.click('[data-act=ntype][data-v=mirrored]')
        hh=await ev(f"(()=>{{const t={L}.t.pos;return [t[0][3],t[1][3]]}})()")
        lin=(hh[0][2]**2+hh[0][3]**2)**.5; lout=(hh[1][0]**2+hh[1][1]**2)**.5
        check('mirrored: equal opposite handles', abs(lin-lout)<0.05 and lin>1 and abs(hh[0][2]+hh[1][0])<0.05, (lin,lout))
        x0=await ev(f"{L}.t.pos[1][1][0]")
        await pg.fill('#np-x', str((await ev("+document.getElementById('np-x').value"))+10)); await pg.press('#np-x','Tab')
        check('node position field moves the node', abs(await ev(f"{L}.t.pos[1][1][0]")-x0-10)<0.01)
        # miter
        await ev(f"hi.select('{tid}')")
        await pg.click('[data-tx="x:stroke-linejoin"][data-v=round]')
        m=await ev("(()=>{const i=document.getElementById('x-miter');return [!!i, i&&i.disabled, i&&i.closest('.row').querySelector('.rl').textContent]})()")
        check('miter in line join row, disabled for round', m==[True,True,'Line join'], m)
        # local fonts
        await pg.click('#g-family'); await pg.wait_for_timeout(100)
        await pg.click('#fontPop [data-fpact=local]'); await pg.wait_for_timeout(400)
        heads=await ev("[...document.querySelectorAll('#fontPop .fp-head')].map(h=>h.childNodes[0].textContent)")
        check('local fonts last, after the Google Fonts groups', heads[-1]=='ON THIS COMPUTER' and 'LATIN' in heads and 'My Local Sans' in (await ev("[...document.querySelectorAll('#fontPop .fp-opt')].map(o=>o.dataset.font).join('|')")), heads)
        await pg.locator('#fontPop .fp-opt[data-font="My Local Sans"]').first.click(); await pg.wait_for_timeout(200)
        check('local font applied', await ev(f"document.getElementById('e-{tid}-s').getAttribute('font-family')")=="'My Local Sans', sans-serif")
        await ev("st.doc.ex.fonts='outline'; B.openExport()"); await pg.wait_for_timeout(1500)
        prev=await ev("document.getElementById('xprev').innerHTML")
        check('local font exported as outlines', 'Good morning' not in prev and await ev("!document.getElementById('xFontRow').hidden"))
        await pg.click('#xFonts [data-v=embed]'); await pg.wait_for_timeout(1500)
        prev=await ev("document.getElementById('xprev').innerHTML")
        check('local font embedded', 'My Local Sans' in prev and 'base64' in prev and 'format(\\"woff\\")' in prev.replace('"','\\"') or 'format("woff")' in prev)
        await pg.keyboard.press('Escape')
        await pg.click('#g-family'); await pg.click('#fontPop [data-fpact=custom]'); await pg.wait_for_timeout(100)
        await pg.fill('#g-fname','Segoe UI'); await pg.press('#g-fname','Tab')
        check('typed font name', await ev(f"{L}.geo.family")=='Segoe UI')
        await ev(f"hi.select('{tid}')"); await ev("document.getElementById('insp').scrollTop=0")
        await pg.screenshot(path=OUT+'te2.png')
        R['errors']=errs; print(json.dumps(R,indent=1)); print('FAILS',F)
        await b.close()
asyncio.run(main())
