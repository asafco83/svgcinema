import asyncio, sys, json, os
from playwright.async_api import async_playwright
OUT=os.environ.get('CIN_OUT','/tmp/svgcinema-shots/'); os.makedirs(OUT, exist_ok=True)
# Select same: the button in the properties panel's header (every layer but bones) with its menu
# (Shapes & text, and Text for text layers, each with the layers' values), the same choices in the
# layer right-click menu and Edit › Select same, matching from several layers, and Text appearance
# for selections with text layers (with shapes too): Mixed values, changes to the text layers only.
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await b.new_page()
        await pg.set_viewport_size({'width':1440,'height':900}); pg.set_default_timeout(8000)
        errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
        base=sys.argv[1] if len(sys.argv)>1 else 'http://localhost:5199/'
        await pg.goto(base, wait_until='domcontentloaded'); await pg.wait_for_timeout(2500)
        await pg.evaluate("async()=>{ window.st=await import('/src/core/state.ts'); window.hi=await import('/src/core/history.ts'); }")
        ev=lambda js, a=None: pg.evaluate(js, a); R={}; F=[]
        def check(n,c,i=None):
            R[n]=('ok' if c else 'FAIL')+('' if i is None else f' {i}')
            if not c: F.append(n)
        lid=lambda n: ev(f"st.doc.layers.find(l=>l.name==={json.dumps(n)}).id")
        names=lambda: ev("[...st.S.selSet].map(id=>st.layerById(id).name)")
        menu=lambda: ev("[...document.querySelectorAll('#layermenu .ctx-h, #layermenu button')].filter(e=>e.checkVisibility()).map(e=>e.matches('.ctx-h')?'#'+e.textContent:[e.querySelector('span').textContent, (e.querySelector('kbd.lm-val')||{}).textContent||''])")
        ground=await lid('Ground')
        await ev(f"hi.select('{ground}')"); await pg.wait_for_timeout(200)
        hb=await ev("(()=>{const h=document.querySelector('#insp .insp-head'),b=document.getElementById('bSame');return b?[...h.children].map(c=>c.id||c.className):null})()")
        check('the header: name, Select same, type chip', hb==['ln','bSame','chip'], hb)
        await pg.click('#bSame'); await pg.wait_for_timeout(200)
        m=await menu()
        check('a rectangle: only Shapes & text, with its values', m[0]=='#Shapes & text' and ['Shape','Rectangle'] in m and not any(x=='#Text (selects text layers only)' for x in m), m)
        pos=await ev("(()=>{const b=document.getElementById('bSame').getBoundingClientRect(),m=document.getElementById('layermenu').getBoundingClientRect();return [document.getElementById('bSame').getAttribute('aria-expanded'), Math.round(m.right-b.right), Math.round(m.top-b.bottom)]})()")
        check('the button shows the menu is open, the menu sits under it, right edges lined up', pos[0]=='true' and abs(pos[1])<2 and 0<=pos[2]<=8, pos)
        check('items sit indented under the title', await ev("parseFloat(getComputedStyle(document.querySelector('#layermenu .lm-it.ind > button')).paddingLeft)")==20)
        await pg.screenshot(path=OUT+'select-same.png')
        await pg.click('#bSame'); await pg.wait_for_timeout(150)
        check('clicking the button again closes it', await ev("document.getElementById('layermenu').hidden && document.getElementById('bSame').getAttribute('aria-expanded')==='false'"))
        await pg.click('#bSame'); await pg.click('#layermenu [data-lm="same:type"]'); await pg.wait_for_timeout(200)
        got=await names(); want=await ev("st.doc.layers.filter(l=>l.type==='rect'&&!l.hid&&!l.lock).map(l=>l.name)")
        check('Shape: every visible rectangle', sorted(got)==sorted(want) and len(got)>1, (got, want))
        check('…the one it started from stays the primary', await ev("st.S.sel")==ground)
        # several selected: matches any of them; the header has the button after "N layers"
        title=await lid('Title')
        await ev(f"hi.select('{ground}'); hi.select('{title}','toggle')"); await pg.wait_for_timeout(200)
        mh=await ev("[...document.querySelector('#insp .insp-head').children].map(c=>c.id||c.className)")
        check('several layers: the button after "2 layers"', mh==['ih-name ih-multi','bSame','chip'], mh)
        await pg.click('#bSame'); await pg.wait_for_timeout(200)
        m=await menu()
        check('a text layer in the selection adds the Text group', '#Text (selects text layers only)' in m and ['Font family', 'Instrument Serif'] in [x[:2] for x in m if isinstance(x,list)] or any(isinstance(x,list) and x[0]=='Font family' for x in m), m)
        check('values that differ show Mixed', ['Shape','Mixed'] in m, m)
        await pg.click('#layermenu [data-lm="same:type"]'); await pg.wait_for_timeout(200)
        got=await names(); want=await ev("st.doc.layers.filter(l=>(l.type==='rect'||l.type==='text')&&!l.hid&&!l.lock).map(l=>l.name)")
        check('several layers: Shape matches either kind', sorted(got)==sorted(want), (got, want))
        # text-only choice selects only text
        await ev(f"hi.select('{title}')"); await pg.wait_for_timeout(150)
        await pg.click('#bSame'); await pg.click('#layermenu [data-lm="same:font"]'); await pg.wait_for_timeout(200)
        got=await ev("[...st.S.selSet].map(id=>st.layerById(id).type)")
        check('Font family selects text layers only', got and all(t=='text' for t in got), got)
        # bones: no button
        stem=await lid('Stem')
        await ev(f"hi.select('{stem}')"); await pg.wait_for_timeout(150)
        check('a bone: no Select same button', await ev("!document.getElementById('bSame')"))
        # the right-click menu: Select same after Delete, with the same list
        await ev(f"hi.select('{ground}')"); await pg.wait_for_timeout(150)
        await pg.locator('.lp-row.sel').first.click(button='right'); await pg.wait_for_timeout(200)
        top=await ev("[...document.querySelectorAll('#layermenu > .lm-it > button span:first-of-type')].map(s=>s.textContent)")
        i=top.index('Select same') if 'Select same' in top else -1
        check('right-click: Select same right after Delete', i>0 and top[i-1]=='Delete', top[:8])
        await pg.hover('#layermenu [data-lm="same"]'); await pg.wait_for_timeout(200)
        sub=await ev("[...document.querySelectorAll('#layermenu [data-lm=\"same\"] + .lm-sub button span')].map(s=>s.textContent)")
        check('…its submenu is the Select same list', sub[:3]==['Shape','Fill & stroke','Fill color'], sub)
        await pg.click('#layermenu [data-lm="same:type"]'); await pg.wait_for_timeout(200)
        check('…and it selects', len(await names())>1)
        await pg.keyboard.press('Escape')
        # ≡ › Edit › Select same: the same list, Element doesn't repeat it
        await ev(f"hi.select('{title}')"); await pg.wait_for_timeout(150)
        await pg.click('#bMenu'); await pg.hover('#fileMenu [data-sub=edit] > button'); await pg.wait_for_timeout(150)
        await pg.hover('#fileMenu [data-lm="ed:same"]'); await pg.wait_for_timeout(150)
        ed=await ev("[...document.querySelectorAll('#fileMenu [data-lm=\"ed:same\"] + .lm-sub .ctx-h, #fileMenu [data-lm=\"ed:same\"] + .lm-sub button span')].map(s=>s.textContent)")
        check('Edit › Select same: both groups for a text layer', ed[0]=='Shapes & text' and 'Text (selects text layers only)' in ed and 'Text fill & stroke color' in ed, ed)
        el=await ev("(()=>{const s=document.querySelector('#fileMenu [data-sub=element] .lm-sub');return s?[...s.querySelectorAll('button span')].map(x=>x.textContent):[]})()")
        check('Element doesn’t repeat it', 'Select same' not in el, el)
        await pg.keyboard.press('Escape'); await pg.mouse.click(700, 880); await pg.wait_for_timeout(100)
        # Text appearance with a mixed selection
        made=await lid('Made with SVGcinema')
        await ev(f"hi.select('{ground}'); hi.select('{title}','toggle'); hi.select('{made}','toggle')"); await pg.wait_for_timeout(250)
        secs=await ev("[...document.querySelectorAll('#insp .sec > h3')].filter(h=>!h.closest('.sec').hidden).map(h=>h.childNodes[0].textContent.trim())")
        check('a selection with text and a shape shows Text appearance', 'Text appearance' in secs, secs)
        sz=await ev("(()=>{const i=document.getElementById('g-size');return [i.value,i.placeholder]})()")
        sizes=await ev(f"[st.layerById('{title}').geo.size, st.layerById('{made}').geo.size]")
        check('a size that differs shows Mixed', (sizes[0]!=sizes[1] and sz==['', 'Mixed']) or (sizes[0]==sizes[1] and sz[0]==str(sizes[0])), (sz, sizes))
        fam=await ev("document.querySelector('#insp [data-fontpick] span').textContent")
        fams=await ev(f"[st.layerById('{title}').geo.family, st.layerById('{made}').geo.family]")
        check('a font that differs shows Mixed', fam=='Mixed' if fams[0]!=fams[1] else fam!='Mixed', (fam, fams))
        await pg.fill('#g-size','33'); await pg.press('#g-size','Enter'); await pg.wait_for_timeout(200)
        after=await ev(f"[st.layerById('{title}').geo.size, st.layerById('{made}').geo.size, st.layerById('{ground}').geo.size]")
        check('a size change applies to the text layers only', after[0]==33 and after[1]==33 and after[2] is None, after)
        await pg.click('#insp [data-tx="italic"]'); await pg.wait_for_timeout(200)
        it=await ev(f"[!!st.layerById('{title}').geo.italic, !!st.layerById('{made}').geo.italic, st.layerById('{ground}').geo.italic]")
        check('Italic: every text layer, not the shape', it[0] and it[1] and it[2] is None, it)
        check('…as one undo step', await ev("(()=>{const n=st.S.undo.length;return n})()")>0)
        await ev("hi.undo()"); await pg.wait_for_timeout(150)
        check('one undo takes Italic off both', not await ev(f"!!st.layerById('{title}').geo.italic || !!st.layerById('{made}').geo.italic"))
        await pg.click('#insp [data-fontpick]'); await pg.wait_for_timeout(300)
        await pg.click('.fp-opt[data-font="Inter"]'); await pg.wait_for_timeout(300)
        ff=await ev(f"[st.layerById('{title}').geo.family, st.layerById('{made}').geo.family]")
        check('the font list sets the font on every selected text layer', ff==['Inter','Inter'], ff)
        await pg.screenshot(path=OUT+'select-same-multi.png')
        check('no page errors', not errs, errs[:3])
        print(json.dumps(R, indent=1, ensure_ascii=False)); print('FAILS', F)
        await b.close()
asyncio.run(main())
