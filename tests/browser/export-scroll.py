import asyncio, sys, json, os
from playwright.async_api import async_playwright
OUT=os.environ.get('CIN_OUT','/tmp/svgcinema-shots/'); os.makedirs(OUT, exist_ok=True)
# Export › Animated SVG › Playback › Starts › Linked to scroll: the rows it shows and hides, the test
# page in the preview (its scroll drives the player; start and end lines; how much has played), custom
# ranges and smoothing, CSS falling back, the embed note, and the exported SVG on a real page: inline
# (the window's scroll) and in an <object> (measured in the page around it), with the external player too.
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await b.new_page()
        await pg.set_viewport_size({'width':1440,'height':900}); pg.set_default_timeout(10000)
        errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
        base=sys.argv[1] if len(sys.argv)>1 else 'http://localhost:5199/'
        await pg.goto(base, wait_until='domcontentloaded'); await pg.wait_for_timeout(2500)
        await pg.evaluate("async()=>{ window.st=await import('/src/core/state.ts'); window.bd=await import('/src/export/build.ts'); window.imgs=await import('/src/export/images.ts'); }")
        ev=lambda js, a=None: pg.evaluate(js, a); R={}; F=[]
        def check(n,c,i=None):
            R[n]=('ok' if c else 'FAIL')+('' if i is None else f' {i}')
            if not c: F.append(n)
        await ev("localStorage.removeItem('svgcinema:exportKind'); localStorage.removeItem('svgcinema:exportClosed'); Object.assign(st.doc.ex,{mode:'js',player:'embed',size:'resp',trigger:'load'}); delete st.doc.ex.scrub")
        await pg.click('#bExport'); await pg.wait_for_timeout(1200)
        opts=await ev("[...document.querySelectorAll('#xTrig option')].map(o=>o.textContent)")
        check('Starts offers Linked to scroll after On scroll into view', opts==['On load','On mouse over','On click','On scroll into view','Linked to scroll','Programmatic'], opts)
        await pg.select_option('#xTrig','scrub'); await ev("imgs.expReady()"); await pg.wait_for_timeout(300)
        vis=await ev("['xScrubRows','xItRow','xDirRow','xFillRow','xSpeedRow','xOutRow','xsCustom'].map(i=>!document.getElementById(i).hidden)")
        check('its rows show; Repeat, Direction, After the end, Speed and Out hide', vis==[True,False,False,False,False,False,False], vis)
        sc=await ev("[st.doc.ex.scrub, document.getElementById('xsRange').value, document.getElementById('xsSmv').textContent, document.getElementById('xSumPlay').textContent]")
        check('defaults: crosses the window, 0.3 s smoothing; the summary says so', sc[0]['range']=='cross' and sc[0]['sm']==0.3 and sc[1]=='cross' and sc[2]=='0.3 s' and sc[3]=='Linked to scroll · while it crosses the window', sc)
        # the test page
        lay=await ev("(()=>{const w=document.getElementById('xsPage').getBoundingClientRect(),a=document.querySelector('#xsPage .xs-art svg').getBoundingClientRect(),side=document.querySelector('.xs-side').getBoundingClientRect();return [Math.round(w.width),Math.round(w.height),Math.round(a.width),Math.round(side.width)]})()")
        check('the test page fills the pane beside a 132 px side panel; the art fits its column', lay[0]>400 and lay[1]==378 and lay[2]==lay[0]-56 and lay[3]==132, lay)
        tp=await ev("(()=>{const pg=document.getElementById('xsPage'),s=pg&&pg.querySelector('.xs-art svg');return [!!pg, !!(s&&s.player), [...document.querySelectorAll('#xprev .xs-tag')].map(t=>t.textContent), document.getElementById('xPrevLbl').textContent.startsWith('A test page')]})()")
        check('the preview is a test page with the player, start and end lines', tp[0] and tp[1] and tp[2]==['Start · its top here','End · its bottom here'] and tp[3], tp)
        await ev("st.doc.ex.scrub.sm=0; imgs.updateExport()"); await ev("imgs.expReady()"); await pg.wait_for_timeout(300)
        cur=lambda: ev("document.querySelector('#xsPage .xs-art svg').player.currentTime")
        mid=await cur()
        check('it opens with the art in the middle of the window, half played', 1300<mid<1700, mid)
        await ev("document.getElementById('xsPage').scrollTop=0"); await pg.wait_for_timeout(200)
        t0=await cur()
        await ev("const p=document.getElementById('xsPage');p.scrollTop=p.scrollHeight"); await pg.wait_for_timeout(200)
        t1=await cur()
        check('scrolled to the top: the first frame; to the bottom: the last', t0==0 and t1==3000, (t0,t1))
        await pg.wait_for_timeout(200)
        rd=await ev("[document.getElementById('xsPct').textContent, document.getElementById('xsTime').textContent, document.getElementById('xsFill').style.height]")
        check('the side panel shows how much has played', rd==['100%','0:03.00 of 0:03.00','100%'], rd)
        # the mouse wheel over the test page plays it
        await ev("document.getElementById('xsPage').scrollTop=0"); await pg.wait_for_timeout(100)
        box=await pg.locator('#xsPage').bounding_box()
        await pg.mouse.move(box['x']+box['width']/2, box['y']+box['height']/2); await pg.mouse.wheel(0, 500); await pg.wait_for_timeout(400)
        tw=await cur(); st_=await ev("document.getElementById('xsPage').scrollTop")
        check('the mouse wheel over the test page plays it', 0<tw<3000, (tw, st_))
        # custom
        await pg.select_option('#xsRange','custom'); await ev("imgs.expReady()"); await pg.wait_for_timeout(300)
        check('Custom shows Starts when / Ends when', await ev("!document.getElementById('xsCustom').hidden && document.getElementById('xsFp').value==='80' && document.getElementById('xsTe').value==='center'"))
        await pg.select_option('#xsFe','bottom'); await pg.fill('#xsTp','20'); await pg.press('#xsTp','Enter'); await ev("imgs.expReady()"); await pg.wait_for_timeout(300)
        tg=await ev("[...document.querySelectorAll('#xprev .xs-tag')].map(t=>[t.textContent,t.style.top])")
        check('the lines move to the custom range', tg==[['Start · its bottom here','80%'],['End · its centre here','20%']], tg)
        check('…and the export carries it', '{"r":[1,80,0.5,20]}' in await ev("bd.buildExport(null).code"))
        # smoothing
        await ev("(()=>{const s=document.getElementById('xsSm');s.value='0.5';s.dispatchEvent(new Event('input'));s.dispatchEvent(new Event('change'))})()")
        await ev("imgs.expReady()")
        check('smoothing: a number in seconds', await ev("st.doc.ex.scrub.sm===0.5 && document.getElementById('xsSmv').textContent==='0.5 s'"))
        await pg.screenshot(path=OUT+'export-scroll.png')
        # the embed note
        await pg.click('#xTab [data-v="embed"]'); await pg.wait_for_timeout(150)
        check('Embed: the note says where it works', 'Linked to scroll' in await ev("document.getElementById('xFwNote').textContent"))
        await pg.click('#xTab [data-v="preview"]')
        # CSS: not offered, falls back to On load
        await pg.click('#xMode [data-v="css"]'); await pg.wait_for_timeout(300)
        cs=await ev("[[...document.querySelectorAll('#xTrig option')].map(o=>o.value), st.doc.ex.trigger, document.getElementById('xScrubRows').hidden, !document.getElementById('xItRow').hidden, !document.querySelector('#xprev .xs-test')]")
        check('CSS only: no Linked to scroll; back to On load with its rows and plain preview', cs==[['load','hover'],'load',True,True,True], cs)
        await pg.click('#xMode [data-v="js"]'); await pg.select_option('#xTrig','scrub'); await ev("imgs.expReady()")
        # the exported SVG on a real page: inline, following the window's scroll
        await ev("st.doc.ex.scrub={range:'cross',fe:'top',fp:80,te:'center',tp:35,sm:0}")
        code=await ev("bd.buildExport(null).code")
        await pg.keyboard.press('Escape')
        p2=await b.new_page(); await p2.set_viewport_size({'width':1000,'height':800})
        perrs=[]; p2.on('pageerror',lambda e: perrs.append(str(e)))
        await p2.goto(base+'llms.txt')
        await p2.set_content('<!doctype html><body style="margin:0"><div style="height:1200px"></div><div style="width:640px">'+code+'</div><div style="height:1200px"></div></body>')
        await p2.wait_for_timeout(300)
        t=lambda: p2.evaluate("document.querySelector('svg').player.currentTime")
        a0=await t()
        await p2.evaluate("scrollTo(0, 1200+200-400)"); await p2.wait_for_timeout(200)  # its centre at the window's centre
        a1=await t()
        await p2.evaluate("scrollTo(0, 5000)"); await p2.wait_for_timeout(200)
        a2=await t()
        check('inline on a page: follows the window’s scroll (start, middle, end)', a0==0 and 1300<a1<1700 and a2==3000, (a0,a1,a2))
        # in an <object> from the same site
        await p2.set_content('<!doctype html><body style="margin:0"><div style="height:1200px"></div><object id="o" type="image/svg+xml" style="display:block;width:640px;height:400px"></object><div style="height:1200px"></div></body>')
        await p2.evaluate("(c)=>{document.getElementById('o').data=URL.createObjectURL(new Blob([c],{type:'image/svg+xml'}))}", code)
        await p2.wait_for_function("(()=>{try{const d=document.getElementById('o').contentDocument;return d&&d.querySelector('svg')&&d.querySelector('svg').player}catch(e){return false}})()")
        to=lambda: p2.evaluate("document.getElementById('o').contentDocument.querySelector('svg').player.currentTime")
        await p2.evaluate("scrollTo(0,0)"); await p2.wait_for_timeout(200); o0=await to()
        await p2.evaluate("scrollTo(0, 1200+200-400)"); await p2.wait_for_timeout(200); o1=await to()
        await p2.evaluate("scrollTo(0, 5000)"); await p2.wait_for_timeout(200); o2=await to()
        check('in an <object>: measured in the page around it', o0==0 and 1300<o1<1700 and o2==3000, (o0,o1,o2))
        check('no errors on the test pages', not perrs, perrs[:3])
        await p2.close()
        # the external player (the preview boots it with the editor's copy)
        await ev("st.doc.ex.player='external'"); await pg.click('#bExport'); await pg.wait_for_timeout(300); await ev("imgs.updateExport()"); await ev("imgs.expReady()"); await pg.wait_for_timeout(300)
        ex=await ev("(()=>{const s=document.querySelector('#xsPage .xs-art svg');const j=JSON.parse(s.querySelector('script[data-cin]').textContent);return [j.f, j.t, !!s.player]})()")
        check('external player: format 2, and it plays with the scroll in the preview', ex==[2,'scrub',True], ex)
        await ev("const p=document.getElementById('xsPage');p.scrollTop=p.scrollHeight"); await pg.wait_for_timeout(300)
        check('…to the last frame at the bottom', await cur()==3000)
        await pg.keyboard.press('Escape')
        await ev("Object.assign(st.doc.ex,{player:'embed',trigger:'load'})")
        check('no page errors', not errs, errs[:3])
        print(json.dumps(R, indent=1, ensure_ascii=False)); print('FAILS', F)
        await b.close()
asyncio.run(main())
