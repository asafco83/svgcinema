import asyncio, sys, json, os
from playwright.async_api import async_playwright
OUT=os.environ.get('CIN_OUT','/tmp/svgcinema-shots/'); os.makedirs(OUT, exist_ok=True)
# The Presets window: opening it, groups and tiles that fit the selection, the timeline preview (span,
# replaced keys), applying (double-click / Apply), stagger, the toast's Undo, the main menu entry.
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await b.new_page(viewport={'width':1440,'height':900}); pg.set_default_timeout(5000)
        errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
        await pg.goto((sys.argv[1] if len(sys.argv)>1 else 'http://localhost:5199/')); await pg.wait_for_timeout(2500)
        await pg.evaluate("async()=>{ window.st=await import('/src/core/state.ts'); window.hi=await import('/src/core/history.ts'); }")
        ev=pg.evaluate; R={}; F=[]
        def check(n,c,i=None):
            R[n]=('ok' if c else 'FAIL')+('' if i is None else f' {i}')
            if not c: F.append(n)
        lid=lambda n: ev(f"st.doc.layers.find(l=>l.name==='{n}').id")
        title=await lid('Title'); sun=await lid('Sun')
        await ev(f"hi.select('{title}'); hi.setTime(0.5)"); await pg.wait_for_timeout(150)
        await pg.click('#lAnim'); await pg.wait_for_timeout(100)
        check('Animate starts with Presets…', (await ev("document.querySelector('#animMenu button').textContent")).startswith('✦Presets'))
        await pg.click('#animMenu [data-presets]'); await pg.wait_for_timeout(200)
        check('the Presets window opens', await ev("!!document.getElementById('presetPop')"))
        grp=await ev("[...document.querySelectorAll('#presetPop .pr-grp span')].map(s=>s.childNodes[0].textContent)")
        check('groups that fit a text layer (no Strokes)', grp==['Entrances','Exits','Emphasis','Color','Filters'], grp)
        check('Filters says JS export only, its tiles carry a JS badge', 'JS export only' in await ev("document.querySelector('[data-pgroup=filter]').textContent"))
        await pg.click('[data-pgroup=filter]'); await pg.wait_for_timeout(100)
        check('…', await ev("document.querySelectorAll('#presetPop .pr-tile .pr-js').length")==5)
        await pg.click('[data-pgroup=enter]'); await pg.wait_for_timeout(100)
        tiles=await ev("[...document.querySelectorAll('#presetPop .pr-tile span')].map(s=>s.textContent)")
        check('Entrances: fade, slides, pop, zoom, drop, rotate, flip', tiles==['Fade in','Slide up','Slide down','Slide left','Slide right','Pop in','Zoom in','Drop in','Rotate in','Flip in','Elastic in','Spiral in','Skew in','Unfold'], tiles)
        tr=await ev("document.querySelector('#presetPop [data-preset=slide-up] .pr-tracks').textContent")
        check('each tile says which tracks it animates', tr=='Position · Opacity', tr)
        check('each tile plays its preset', await ev("document.querySelector('#presetPop [data-preset=slide-up] .pv').getAnimations().length")==1)
        # Title has opacity keys at 1s and 1.8s: a fade in from 0.5s for 0.6s replaces the one at 1s
        await pg.hover('[data-preset=fade-in]'); await pg.wait_for_timeout(150)
        check('hovering previews the span on the timeline', await ev(f"document.querySelectorAll('.tl-row[data-lid=\"{title}\"] .pv-span').length")>=1)
        check('and outlines the keys it would replace in red', await ev("document.querySelectorAll('.kf.rep').length")==1, await ev("document.querySelectorAll('.kf.rep').length"))
        await pg.click('[data-preset=fade-in]'); await pg.wait_for_timeout(100)
        check('choosing a tile sets its length and describes what it does', await ev("document.getElementById('prLen').value")=='0.6' and 'replaces 1 keyframe' in await ev("document.getElementById('prNote').textContent"), await ev("document.getElementById('prNote').textContent"))
        check('…the replace warning in red', await ev("getComputedStyle(document.querySelector('#prNote .pr-warn')).color")!=await ev("getComputedStyle(document.getElementById('prNote')).color"))
        check('Stagger is hidden for one layer', await ev("document.getElementById('prStagRow').hidden"))
        await pg.screenshot(path=OUT+'presets.png')
        await pg.click('#prApply'); await pg.wait_for_timeout(200)
        ops=await ev(f"st.layerById('{title}').t.op.map(q=>[q[0],q[1]])")
        check('Apply writes the keys and closes the window', ops[0]==[0.5,0] and not await ev("!!document.getElementById('presetPop')"), ops)
        check('a toast says what it replaced, with Undo', 'Replaced 1 keyframe' in await ev("document.getElementById('toast').textContent") and await ev("!!document.querySelector('#toast .toast-act')"))
        check('the preview is gone', await ev("document.querySelectorAll('.pv-span').length")==0)
        await pg.click('#toast .toast-act'); await pg.wait_for_timeout(150)
        check('Undo in the toast puts it back', await ev(f"st.layerById('{title}').t.op.map(q=>q[0])")==[1,1.8])
        # several layers, stagger, double-click, lengthening
        await ev(f"hi.selectMany(['{title}','{sun}']); hi.setTime(2.8)"); await pg.wait_for_timeout(100)
        await pg.click('#bMenu'); await pg.hover('#fileMenu [data-sub=animate] > button'); await pg.wait_for_timeout(150)
        await pg.click('#fileMenu [data-lm=presets]'); await pg.wait_for_timeout(200)
        check('the main menu’s Animate ▸ Presets… opens it too', await ev("!!document.getElementById('presetPop')"))
        check('Stagger shows for several layers', not await ev("document.getElementById('prStagRow').hidden"))
        await pg.click('[data-pgroup=emph]'); await pg.dblclick('[data-preset=pulse]'); await pg.wait_for_timeout(200)
        t0=await ev(f"st.layerById('{title}').t.scl[0][0]"); t1=await ev(f"st.layerById('{sun}').t.scl.find(q=>q[0]>=2.8)[0]")
        check('double-click applies, the second layer 0.1 s later', abs(t0-2.8)<1e-6 and abs(t1-2.9)<1e-6, (t0,t1))
        check('running past the end lengthens the animation', abs(await ev("st.doc.dur")-3.7)<1e-6, await ev("st.doc.dur"))
        await ev("hi.undo()"); await pg.wait_for_timeout(100)
        check('one undo step removes it all', await ev("st.doc.dur")==3 and await ev(f"!st.layerById('{title}').t.scl"))
        # Esc closes
        await pg.click('#lAnim'); await pg.click('#animMenu [data-presets]'); await pg.keyboard.press('Escape'); await pg.wait_for_timeout(100)
        check('Esc closes it', not await ev("!!document.getElementById('presetPop')"))
        check('no page errors', not errs, errs[:3])
        print(json.dumps(R, indent=1, ensure_ascii=False)); print('FAILS', F)
        await b.close()
asyncio.run(main())
