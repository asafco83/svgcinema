import asyncio, sys, json
from playwright.async_api import async_playwright
import os
OUT=os.environ.get('CIN_OUT','/tmp/svgcinema-shots/'); os.makedirs(OUT, exist_ok=True)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await b.new_page(device_scale_factor=2)
        await pg.set_viewport_size({'width':1440,'height':1000}); pg.set_default_timeout(6000)
        errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
        await pg.goto((sys.argv[1] if len(sys.argv)>1 else 'http://localhost:5199/')); await pg.wait_for_timeout(2500)
        await pg.evaluate("async()=>{ window.st=await import('/src/core/state.ts'); window.hi=await import('/src/core/history.ts'); window.K=await import('/src/core/constants.ts'); window.TR=await import('/src/ui/tools-rail.ts')}")
        ev=lambda js: pg.evaluate(js); R={}; F=[]
        def check(n,c,i=None):
            R[n]=('ok' if c else 'FAIL')+('' if i is None else f' {i}')
            if not c: F.append(n)
        async def drag(a,b2,steps=6):
            await pg.mouse.move(*a); await pg.mouse.down(); await pg.mouse.move(*b2,steps=steps); await pg.mouse.up(); await pg.wait_for_timeout(120)
        handle=lambda k: ev(f"(()=>{{const e=document.querySelector('#overlay [data-h={k}]');if(!e)return null;const r=e.getBoundingClientRect();return [r.x+r.width/2,r.y+r.height/2]}})()")
        await ev("hi.setTime(2)")
        tid=await ev("st.doc.layers.find(l=>l.name==='Title').id"); L=f"st.layerById('{tid}')"
        await ev(f"hi.select('{tid}')"); await pg.wait_for_timeout(100)
        # selected: side handle scales like any layer
        h=await handle('e'); s0=await ev(f"K.valueAt({L},'scl',st.S.time)[0]")
        await drag(h,(h[0]+60,h[1]))
        check('selected: side handle scales', await ev(f"K.valueAt({L},'scl',st.S.time)[0]")>s0 and not await ev(f"!!{L}.geo.wrap"), await ev(f"[{L}.b.scl,{L}.geo.wrap]"))
        await pg.keyboard.press('Control+z')
        # enter edit mode
        r=await ev(f"(()=>{{const r=document.getElementById('e-{tid}-s').getBoundingClientRect();return [r.x+r.width*0.08,r.y+r.height/2]}})()")
        await pg.mouse.dblclick(*r); await pg.wait_for_timeout(200)
        check('edit mode', await ev("document.activeElement && document.activeElement.className==='cin-tedit'"))
        check('edit box handles only', await handle('tbe') is not None and await handle('tbw') is not None and await handle('e') is None and await handle('nw') is None)
        check('text stays visible with its styles', await ev(f"!document.getElementById('e-{tid}-s').getAttribute('visibility') && getComputedStyle(document.querySelector('.cin-tedit')).color==='rgba(0, 0, 0, 0)'"))
        await pg.screenshot(path=OUT+'te3-edit.png', clip={'x':r[0]-60,'y':r[1]-70,'width':420,'height':140})
        # drag the right edit handle narrower: Keep width turns on, text wraps, still typing
        h=await handle('tbe'); x0=await ev(f"{L}.geo.x")
        await drag(h,(h[0]-140,h[1]))
        g=await ev(f"[{L}.geo.wrap,{L}.geo.ww,document.querySelectorAll('#e-{tid}-s tspan').length,JSON.stringify({L}.b.scl)]")
        check('edit handle sets the width and Keep width', g[0] and g[2]>1 and g[3]=='[1,1]', g)
        check('still editing after resizing', await ev("document.activeElement && document.activeElement.className==='cin-tedit'"))
        await pg.keyboard.press('Control+End'); await pg.keyboard.type(' more')
        check('typing continues', (await ev(f"{L}.geo.text")).endswith(' more'))
        h=await handle('tbw'); right=await ev(f"{L}.geo.x+{L}.geo.ww")
        await drag(h,(h[0]-50,h[1]))
        check('left handle keeps the right edge', abs(await ev(f"{L}.geo.x+{L}.geo.ww")-right)<0.6, (right, await ev(f"{L}.geo.x+{L}.geo.ww")))
        # editor box follows the text box
        ta=await ev("(()=>{const b=document.querySelector('.cin-tedit').getBoundingClientRect();return [b.x,b.width]})()")
        bx=await ev("(()=>{const p=document.querySelector('#overlay .ov-box').getBoundingClientRect();return [p.x,p.width]})()")
        check('editor matches the box', abs(ta[0]-bx[0])<2 and abs(ta[1]-bx[1])<2, (ta,bx))
        await pg.keyboard.press('Escape')
        check('back to selected: scale handles', await handle('e') is not None and await handle('tbe') is None)
        # text tool single click enters edit mode
        await ev("TR.pickTool('text')")
        r=await ev(f"(()=>{{const r=document.getElementById('e-{tid}-s').getBoundingClientRect();return [r.x+r.width*0.1,r.y+r.height*0.3]}})()")
        await pg.mouse.click(*r); await pg.wait_for_timeout(150)
        check('text tool click edits', await ev("document.activeElement && document.activeElement.className==='cin-tedit'") and await ev("st.S.tool")=='select')
        await pg.keyboard.press('Escape')
        # corner radius animatable: rect
        await ev("TR.pickTool('rect')"); await drag((800,450),(900,550)); await ev("TR.pickTool('select')")
        rid=await ev("st.S.sel")
        await ev("hi.setTime(0)"); await pg.click('[data-kb=rad]')
        await ev("hi.setTime(1)"); await pg.wait_for_timeout(80)
        await pg.fill('#sh-rad','30'); await pg.press('#sh-rad','Tab')
        tr=await ev(f"JSON.stringify(st.layerById('{rid}').t.rad)")
        await ev("hi.setTime(0.5)"); await pg.wait_for_timeout(80)
        rx=await ev(f"+document.getElementById('e-{rid}-s').getAttribute('rx')")
        check('rect radius keys and animates', tr and '30' in tr and 0<rx<30, (tr,rx))
        check('slider shows animated value', abs(float(await ev("document.getElementById('sh-rad').value"))-rx)<0.01)
        # polygon radius animatable
        await ev("TR.pickTool('polygon')"); await drag((500,450),(500,380)); await ev("TR.pickTool('select')")
        pid=await ev("st.S.sel")
        await ev("hi.setTime(0)"); await pg.click('[data-kb=rad]')
        await ev("hi.setTime(1)"); await pg.wait_for_timeout(80)
        await pg.fill('#sh-rad','15'); await pg.press('#sh-rad','Tab')
        n=await ev(f"document.getElementById('e-{pid}-s').getAttribute('d').split('C').length")
        await ev("hi.setTime(0.5)"); await pg.wait_for_timeout(80)
        check('polygon radius animates (curves appear)', n>4 and await ev(f"!!st.layerById('{pid}').t.rad"), n)
        check('polygon settings still shown', await ev("[...document.querySelectorAll('#insp h3')].some(h=>h.textContent.startsWith('Polygon'))"))
        await ev("hi.setTime(0)"); await pg.wait_for_timeout(80)
        # line ends keyable separately
        await ev("TR.pickTool('line')"); await drag((450,600),(650,640)); await ev("TR.pickTool('select')")
        lid=await ev("st.S.sel")
        await pg.click('[data-kb=p1]')
        await ev("hi.setTime(1)"); await pg.wait_for_timeout(80)
        y=float(await ev("document.getElementById('ln-1-1').value"))
        await pg.fill('#ln-1-1', str(y-80)); await pg.press('#ln-1-1','Tab')
        t=await ev(f"Object.keys(st.layerById('{lid}').t)")
        check('line end keyed alone', t==['p1'], t)
        await ev("hi.setTime(0.5)"); await pg.wait_for_timeout(80)
        mid=float(await ev("document.getElementById('ln-1-1').value"))
        check('line end animates', y-80<mid<y, (y,mid))
        menu=await ev("(async()=>{const m=await import('/src/ui/animate-menu.ts');return m.ANIM_GROUPS.flat().map(x=>x[0])})()")
        check('animate menu lists radius and line ends', all(k in menu for k in ['rad','p0','p1']))
        R['errors']=errs; print(json.dumps(R,indent=1)); print('FAILS',F)
        await b.close()
asyncio.run(main())
